    for sid, scene, st, wh, what in P:
        if st is None:
            t0 = round(WE(len(WORDS) - 1) + 0.06, 3)
        elif isinstance(st, float):
            t0 = st
        else:
            t0 = W(st)
        shots.append(dict(id=sid, scene=scene, t0=t0, what=what, group="ext_a", **({"whip": True} if wh else {})))
    for a, b in zip(shots, shots[1:]):
        a["t1"] = b["t0"]
    shots[-1]["t1"] = END
    shots[0]["hook"] = True
    shots[0]["hit_word"] = 0
