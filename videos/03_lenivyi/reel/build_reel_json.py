def ev_ok(ev, b):
    kind, _, name = str(ev).partition(":"); bb = beats[b]
    if kind == "gaps": return bool(bb.get("gaps"))
    if kind == "fx": return any(name in (e.get("kind"), e.get("name")) or (name == "strike" and "strike_at" in e) for e in bb["fx"])
    if kind == "shot": return any(name in (s.get("src"), s.get("kind"), s.get("sound")) for s in bb["shots"])
    return False

def remap(v):
    """Решение эп.01 → та же роль фразы в этом рилсе."""
    if isinstance(v, int) and not isinstance(v, bool): return sorted({MAP[v]})
    if isinstance(v, list): return sorted({MAP[x] for x in v if isinstance(x, int)})
    if isinstance(v, dict) and "beats" in v:
        bs = sorted({MAP[x] for x in v["beats"]})
        out = {k: x for k, x in v.items() if k not in ("beats", "quote", "evidence")}
        if v.get("evidence") and any(ev_ok(v["evidence"], b) for b in bs):
            return dict(out, beats=bs, evidence=v["evidence"])
        return dict(out, beats=bs[:1], quote=QUOTE[bs[0]])
    return v

