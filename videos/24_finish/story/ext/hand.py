"""Правая рука Димы с ручкой (горчичный рукав худи). Рисуется в своей системе: кончик ручки в (0, 0), ручка вдоль +u
(вправо), кисть ниже-правее ручки (+v); потом поворачивается углом ang (ручка уходит вверх-вправо). Порядок слоёв как у
настоящей хватки: средний палец под ручкой, ручка, ладонь-тыл, большой палец спереди, указательный сверху на ручке."""
import math

import lib
from lib import INK, blob, f, line, shape

SKIN, SKIN_SH, SKIN_SH2, NAIL = "#ecc4a2", "#d39f83", "#bf8a74", "#f6dccb"
HOOD, HOOD_SH, HOOD_SH2, FOLD = "#d4a23e", "#a97b25", "#8c6219", "#6b4a12"


def _P(pts, ang):
    c, s = math.cos(math.radians(ang)), math.sin(math.radians(ang))
    return [((p[0] * c - p[1] * s), (p[0] * s + p[1] * c)) + ((1,) if len(p) > 2 and p[2] else ()) for p in pts]


def pen(ang, sd=0):
    s = []
    P = lambda pts: _P(pts, ang)
    # конус и стержень
    s.append(shape(P([(2, 0, 1), (34, -10, 1), (34, 10, 1)]), "#c9ced8", blob(P([(2, 0), (34, 2), (34, 10)]), "#8e95a5"), w=2.6, seed=sd + 1))
    s.append(shape(P([(0, 0, 1), (8, -2.6, 1), (8, 2.6, 1)]), "#26356f", "", w=1.6, seed=sd + 2))
    # резиновый держатель
    s.append(shape(P([(32, -12, 1), (128, -14, 1), (128, 14, 1), (32, 12, 1)]), "#2b2f3a",
                   blob(P([(32, 4), (128, 5), (128, 14), (32, 12)]), "#17191f") + "".join(
                       line(P([(44 + k * 14, -11), (44 + k * 14, 11)]), 2, "#3f4554", taper=.1, wmin=.8, seed=sd + 10 + k) for k in range(6)),
                   w=3.2, seed=sd + 3))
    # корпус синий до конца, колпачок с клипом
    s.append(shape(P([(126, -14, 1), (330, -14, 1), (342, -8), (344, 0), (342, 8), (330, 14, 1), (126, 14, 1)]), "#2f5fb0",
                   blob(P([(126, 4), (340, 4), (340, 14), (126, 14)]), "#1f4280") + line(P([(140, -7), (320, -7)]), 4, "#8fb3ee", seed=sd + 4, op=.9),
                   w=3.4, seed=sd + 5))
    s.append(shape(P([(250, -14, 1), (250, -22, 1), (334, -22, 1), (338, -17, 1), (334, -14, 1)]), "#c9ced8", "", w=2.6, seed=sd + 6))
    return "".join(s)


def hand(ang, sd=0, curl=0.0):
    """curl 0..1 — пальцы чуть сильнее прижимают ручку (на нажиме галочки)."""
    P = lambda pts: _P(pts, ang)
    s = []
    # ── рукав (сзади всего): уходит вниз-вправо за кадр
    sleeve = [(330, 100, 1), (384, 26, 1), (470, 50), (600, 150), (740, 280, 1), (560, 500, 1), (430, 330), (360, 200)]
    inner = blob(P([(360, 200), (450, 190), (600, 330), (560, 500), (430, 330)]), HOOD_SH, .9)
    inner += line(P([(390, 40), (470, 140), (540, 230)]), 4, FOLD, seed=sd + 70, op=.7)
    inner += line(P([(380, 230), (450, 200), (500, 260)]), 3.4, FOLD, seed=sd + 71, op=.6)
    # манжета — резинка
    cuff = [(284, 66, 1), (340, -6, 1), (390, 26, 1), (334, 104, 1)]
    s.append(shape(P(sleeve), HOOD, inner, w=5.2, seed=sd + 72))
    # ── запястье/предплечье в манжете
    wrist = [(240, -20), (320, -4), (340, 50), (290, 96), (240, 90)]
    s.append(shape(P(wrist), SKIN, blob(P([(260, 80), (300, 60), (340, 50), (290, 96), (240, 90)]), SKIN_SH, .9), w=4.6, seed=sd + 60))
    s.append(shape(P(cuff), HOOD_SH, "".join(line(P([(298 + k * 11, 58 - k * 1), (322 + k * 11, 24 - k * 1)]), 2.4, FOLD, seed=sd + 80 + k, op=.8)
                                            for k in range(5)), w=4.6, seed=sd + 73))
    # ── ладонь за согнутыми пальцами (без просветов бумаги между ними)
    s.append(shape(P([(60, 22), (170, 0), (210, 60), (210, 126), (150, 124), (100, 96), (66, 50)]), SKIN_SH2, "", w=4.0, seed=sd + 19))
    # ── средний палец под ручкой: ручка лежит на нём, кончик виден снизу у конуса
    mid = [(170, 6), (130, 14), (92, 20), (60, 20), (44, 28), (48, 42), (70, 46), (104, 44), (146, 46), (176, 40)]
    s.append(shape(P(mid), SKIN, blob(P([(48, 40), (70, 46), (104, 44), (146, 46), (176, 40), (170, 30), (100, 34)]), SKIN_SH, .9) +
                   line(P([(98, 22), (100, 42)]), 2.4, SKIN_SH2, seed=sd + 21, op=.8), w=4.2, seed=sd + 20))
    s.append(shape(P([(46, 30), (58, 24), (64, 36), (52, 42)]), NAIL, "", w=2, seed=sd + 22))
    # ── ручка
    s.append(pen(ang, sd + 100))
    # ── безымянный и мизинец поджаты к ладони: согнутые «колбаски» ниже среднего
    ring = [(180, 46), (140, 54), (110, 62), (100, 78), (112, 90), (146, 86), (184, 84)]
    s.append(shape(P(ring), SKIN, blob(P([(104, 80), (112, 90), (146, 86), (184, 84), (180, 74), (130, 76)]), SKIN_SH, .9) +
                   line(P([(138, 58), (140, 82)]), 2.4, SKIN_SH2, seed=sd + 31, op=.7), w=4.2, seed=sd + 30))
    pinky = [(186, 84), (152, 92), (134, 104), (140, 118), (168, 118), (196, 112)]
    s.append(shape(P(pinky), SKIN, blob(P([(136, 110), (140, 118), (168, 118), (196, 112), (190, 104), (160, 108)]), SKIN_SH, .9),
                   w=4.0, seed=sd + 32))
    # ── тыл кисти: ряд костяшек слева (у пальцев), к запястью сужается
    back = [(146, -40), (180, -50), (232, -44), (282, -16), (304, 30), (290, 80), (246, 112), (200, 120), (184, 98), (182, 70),
            (176, 40), (164, 8), (148, -16)]
    inner = blob(P([(200, 118), (246, 84), (304, 30), (290, 80), (246, 112)]), SKIN_SH, .9)
    inner += blob(P([(182, 70), (200, 60), (204, 110), (190, 118)]), SKIN_SH, .6)
    inner += line(P([(204, -26), (238, 8), (266, 50)]), 2.6, SKIN_SH2, seed=sd + 41, op=.7)       # сухожилия
    inner += line(P([(232, -36), (268, -6), (292, 30)]), 2.4, SKIN_SH2, seed=sd + 42, op=.6)
    s.append(shape(P(back), SKIN, inner, w=5.0, seed=sd + 40))
    # костяшки — короткие дуги вдоль левого края
    for k, (u, v) in enumerate([(168, -34), (184, 8), (196, 48)]):
        s.append(line(P([(u + 6, v - 10), (u + 14, v), (u + 6, v + 10)]), 2.6, SKIN_SH2, seed=sd + 45 + k, op=.8))
    # ── большой палец: основание у запястья снизу, подушечка прижимает ручку снизу-спереди
    thumb = [(222, 96), (184, 70), (146, 44), (114, 24), (94, 12), (80, 16), (80, 32), (102, 46), (136, 72), (174, 104), (212, 128)]
    tin = blob(P([(82, 30), (102, 46), (136, 72), (174, 104), (212, 128), (196, 108), (140, 64), (100, 36)]), SKIN_SH, .9)
    tin += line(P([(122, 32), (116, 52)]), 2.4, SKIN_SH2, seed=sd + 51, op=.8)                       # сгиб сустава
    s.append(shape(P(thumb), SKIN, tin, w=4.6, seed=sd + 50))
    s.append(shape(P([(82, 18), (96, 14), (100, 24), (86, 28)]), NAIL, "", w=2.2, seed=sd + 52))
    # ── указательный: лежит на ручке сверху, от костяшки к кончику; горбик в среднем суставе
    cu = 4 * curl
    idx = [(156, -38), (122, -52 - cu), (86, -46 - cu), (56, -30), (38, -16), (32, -4), (42, 4), (66, -2), (96, -10), (126, -8), (160, -2)]
    iin = blob(P([(40, -8), (66, -2), (96, -10), (126, -8), (160, -2), (156, -16), (100, -22), (60, -16)]), SKIN_SH, .9)
    iin += line(P([(84, -40), (90, -22)]), 2.4, SKIN_SH2, seed=sd + 61, op=.8)
    iin += line(P([(122, -48), (124, -26)]), 2.4, SKIN_SH2, seed=sd + 62, op=.7)
    s.append(shape(P(idx), SKIN, iin, w=4.6, seed=sd + 63))
    s.append(shape(P([(38, -10), (52, -18), (60, -10), (46, -2)]), NAIL, "", w=2.2, seed=sd + 64))
    return "".join(s)


def draw(x, y, ang, sc=1.0, sd=0, curl=0.0):
    return f'<g transform="translate({f(x)} {f(y)}) scale({f(sc)})">{hand(ang, sd, curl)}</g>'
