"""Костюм кота-диктора рилса 132: тёмно-синий пиджак, белая рубашка, красный галстук. Рисуется ВНУТРИ рисунка кота
(common/cat.py: wear_body — в группе тела, под передними лапами), поэтому дышит, сжимается и прыгает вместе с котом.
Морда открыта: воротник у шеи (y ≥ 1140), голова рисуется поверх. Подменяет CT.draw — кот в костюме во всех планах,
включая призыв cta_code."""
import lib
from lib import blob, line, shape
from ink import ellipse_pts

JK, JK_SH, JK_HI, SHIRT, TIE, TIE_SH = "#2c3a5e", "#1e2944", "#3c4c76", "#f7f5ef", "#d8352a", "#a8241c"


def suit():
    o = []
    body = [(784, 1140), (888, 1140), (924, 1182), (940, 1246), (930, 1302, 1), (742, 1302, 1), (732, 1246), (748, 1182)]
    inner = blob([(870, 1150), (932, 1190), (940, 1300), (884, 1300), (892, 1220)], JK_SH, .9)
    o.append(shape(body, JK, inner, w=4.6, seed=13200))
    # рубашка клином и воротничок
    o.append(shape([(800, 1142, 1), (872, 1142, 1), (836, 1240, 1)], SHIRT, "", w=3.4, seed=13201))
    for sx, sd in ((-1, 13202), (1, 13203)):
        o.append(shape([(836, 1150, 1), (836 + sx * 38, 1140, 1), (836 + sx * 30, 1172, 1)], SHIRT, "", w=3.0, seed=sd))
    # галстук: узел и лопасть
    o.append(shape([(824, 1150, 1), (848, 1150, 1), (844, 1168, 1), (828, 1168, 1)], TIE, "", w=3.0, seed=13204))
    o.append(shape([(828, 1168, 1), (844, 1168, 1), (854, 1226), (836, 1246, 1), (818, 1226)], TIE, blob([(838, 1170), (846, 1170), (852, 1224), (840, 1236)], TIE_SH, .8),
                   w=3.2, seed=13205))
    # лацканы
    for sx, sd in ((-1, 13206), (1, 13207)):
        lap = [(836 + sx * 4, 1240), (836 + sx * 40, 1144), (836 + sx * 62, 1150), (836 + sx * 46, 1190), (836 + sx * 56, 1200)]
        o.append(shape(lap, JK_HI, "", w=3.4, seed=sd))
    # пуговица и нагрудный карман с платочком
    o.append(shape(ellipse_pts(836, 1262, 7, 7, 8), "#11151f", "", w=1.8, seed=13208))
    o.append(line([(880, 1200), (914, 1200)], 3, "#11151f", taper=0, wmin=1, seed=13209))
    o.append(shape([(886, 1200, 1), (896, 1186, 1), (906, 1200, 1)], SHIRT, "", w=2.2, seed=13210))
    return "".join(o)


def install(CT):
    if getattr(CT, "_suited", False):
        return
    raw = CT.draw

    def draw(x, y, k, st, t):
        st = dict(st or {})
        st["wear_body"] = suit()      # каждый кадр заново: заливки с обрезкой кладут clipPath в DEFS кадра
        st["sleeve"] = (JK, JK_SH)    # рукава пиджака: лапы выходят из манжет
        return raw(x, y, k, st, t)
    CT.draw = draw
    CT._suited = True
