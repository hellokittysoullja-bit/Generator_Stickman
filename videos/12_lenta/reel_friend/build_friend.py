def ix(text, word):
    """Номер слова фразы (как их считает reel.py: по пробелам, «|» и «*» не слова)."""
    ws = [x.strip("*|.,:;?!«»") for x in text.replace("|", " ").split()]
    return next(i for i, x in enumerate(ws) if x.lower().startswith(word.lower()))
