"""План рилса 125 «СДВГ-бинго» по голосу: shots.json и sound.json из voice/words.json. python3 plan.py — пересчитать после новой озвучки."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "common"))
import plan_base  # noqa: E402

# клетки: (первое слово пункта, слово отметки)
CELLS = [(6, 8), (9, 11), (12, 17), (18, 22), (23, 30), (31, 33), (34, 37), (38, 44), (45, 49)]
WHAT = ["Сорок открытых вкладок: браузер, вкладки множатся до 40", "Чайник остыл трижды: чайник, пар гаснет, «×3»",
        "Зашёл в комнату и забыл зачем: дверь, над головой вопрос", "Начал три дела, закончил ноль: три папки открыты, «0»",
        "Ответил в голове, но не отправил: облако мысли с ответом, кнопка «отправить» серая",
        "Ключи в холодильнике: холодильник открыт, на полке ключи", "Ночью вдруг стал продуктивным: луна, ноутбук сияет",
        "Таймер на пять минут превратился в час: «5:00» → «60:00»", "Купил ежедневник и не открыл: ежедневник с бантом в пыли"]

P = [("s01", "hook_card", 0.0, False, "ХУК с 0 с: карточка бинго 3×3, клетки подпрыгивают, кот с маркером. Надпись «СДВГ-БИНГО»."),
     ("s02", "lets_see", 1, False, "«Посмотрим, сколько у тебя совпадёт»: кот заносит маркер, счётчик «0/9»."), ]
import json  # noqa: E402
_WS = json.load(open(os.path.join(HERE, "voice", "words.json")))
for i, ((w0, wk), what) in enumerate(zip(CELLS, WHAT)):
    st = round(_WS[w0]["start"] - .12, 3) if i == 8 else w0      # клетка 9 чуть раньше: план клетки 8 иначе 2,52 с
    P.append((f"s{i + 3:02d}", f"cell{i + 1}", st, True, f"Клетка {i + 1}: {what}; кот ставит отметку на слове {wk}."))
P += [("s12", "bingo", 50, True, "«У меня бинго по всем девяти»: Дима крупно с карточкой, все клетки отмечены, вспышка, «БИНГО!»."),
      ("s13", "cta", 56, True, "ПРИЗЫВ: поле комментария с цифрой с первого кадра, карточка и кот."),
      ("s14", "loop", None, True, "ПЕТЛЯ: кадр хука — пустая карточка бинго.")]


def extra(W, WE, T, T1, end):
    return {"title": {"text": "СДВГ-БИНГО", "module": "common/big_title.py", "t_in": 0.0, "t_out": T["s03"], "hits": [0, 2, 5],
                      "why": "надпись хука с кадра 0, тряска на «бинго», «сколько», «совпадёт»"},
            "cells": [{"w0": a, "mark": round(W(b) + .05, 3)} for a, b in CELLS]}


def sfx(W, T):
    out = [("fast_whoosh", "удар хука: влёт камеры", {"t": 0.1}),
           ("riser", "нарастание хука: клетки прыгают", {"t": 0.2}),
           ("level_up", "«бинго!»", {"word": 0, "offset": .6}),
           ("swoosh", "склейка к «посмотрим»", {"t": T["s02"]}),
           ("keyboard_soft", "маркер наготове", {"word": 5})]
    for i, (w0, wk) in enumerate(CELLS):
        sid = f"s{i + 3:02d}"
        out.append(("swoosh_deep" if i % 2 else "swoosh", f"хлёст к клетке {i + 1}", {"t": T[sid]}))
        out.append(("shock" if i in (3, 5) else "keyboard_soft", f"отметка в клетке {i + 1}", {"word": wk, "offset": .05}))
    out += [("swoosh_deep", "хлёст к бинго", {"t": T["s12"]}),
            ("shock", "«бинго»: вспышка", {"word": 52}),
            ("level_up", "«девяти»", {"word": 55}),
            ("swoosh", "хлёст к призыву", {"t": T["s13"]}),
            ("typing", "цифра печатается", {"t": T["s13"] + 0.05, "gain_db": -4}),
            ("keyboard_soft", "«совпало»", {"word": 60}),
            ("swoosh", "хлёст в петлю к хуку", {"t": T["s14"]})]
    return out


if __name__ == "__main__":
    plan_base.build(HERE, "125 «СДВГ-бинго»", P, extra, sfx, keys=[0, 2, 5, 8, 11, 17, 22, 30, 33, 37, 44, 49, 52, 55, 60])
