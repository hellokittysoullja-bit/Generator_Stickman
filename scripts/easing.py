"""Кривые плавности для монтажа (скаляр 0..1, вход обрезается): одна копия на все сборщики.

ease_io — smoothstep: разгон и торможение (переезды, проявления); ease_out — кубическое торможение (въезд, наезд).
У камеры длинного ролика своя векторная ease_io — smootherstep (`camera.ease_io`): её кривая другая, не путать."""


def ease_io(u):
    u = min(1.0, max(0.0, u))
    return u*u*(3 - 2*u)


def ease_out(u):
    u = min(1.0, max(0.0, u))
    return 1 - (1 - u)**3
