#!/bin/bash
# Параллельный рендер 3D-сцены three.js по кадрам (владелец 20.11: «максимально нагрузить процессор»).
# Один headless-Chromium грузит ~2,4 из 4 ядер; два рабочих на разные куски кадров — ~3,7 из 4 (≈1,5× быстрее).
# Использование (из папки сцены): bash scripts/three_render_parallel.sh render98.mjs <всего_кадров> [рабочих=2]
R=$1; N=$2; W=${3:-2}; step=$(( (N + W - 1) / W ))
for ((k=0; k<W; k++)); do a=$((k*step)); b=$(((k+1)*step)); PORT=$((8777+k)) node "$R" $a $b > "render_w$k.log" 2>&1 & done
wait; echo "все $W рабочих закончили"
